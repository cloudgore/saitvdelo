def validate_terms():
    all_terms = [
        term
        for group in TERMS.values()
        for term in group
    ]

    normalized = [
        " ".join(term.casefold().split())
        for term in all_terms
    ]

    if len(all_terms) != 150:
        raise ValueError(
            f"Ожидалось 150 запросов, получено {len(all_terms)}"
        )

    if len(set(normalized)) != 150:
        raise ValueError(
            "В семантической карте есть повторяющиеся запросы"
        )

    if len(TERMS) != 22:
        raise ValueError(
            f"Ожидалось 22 страницы, получено {len(TERMS)}"
        )


