def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--list",
        action="store_true",
        help="Показать все 150 запросов"
    )

    parser.add_argument(
        "--apply",
        action="store_true",
        help="Применить изменения к HTML"
    )

    args = parser.parse_args()

    validate_terms()

    total = sum(len(group) for group in TERMS.values())

    print("Семантических запросов:", total)
    print("Целевых страниц:", len(TERMS))

    if args.list:
        for path, words in TERMS.items():
            print("\n" + path)

            for number, word in enumerate(words, 1):
                print(f"  {number:02d}. {word}")

        return

    check_sitemap()

    changes = []

    # Сначала проверяем ВСЕ страницы.
    # Пока проверка не закончится, ничего
    # не записывается на диск.
    for path in sorted(TERMS):
        target = file_for_url(path)

        original = target.read_text(
            encoding="utf-8-sig"
        )

        updated = update_html(original, path)

        if updated != original:
            changes.append((target, updated))
            print("[ИЗМЕНИТСЯ]", path)
        else:
            print("[БЕЗ ИЗМЕНЕНИЙ]", path)

    print("\nИзменяемых HTML:", len(changes))

    if not args.apply:
        print("Пробная проверка: файлы не изменены.")
        return

    if not changes:
        print("Все изменения уже применены.")
        return

    stamp = datetime.now().strftime(
        "%Y%m%d-%H%M%S-%f"
    )

    backup = ROOT / ".seo-backup" / (
        "semantic150-" + stamp
    )

    # Резервные копии перед записью.
    for file, content in changes:
        destination = backup / file.relative_to(ROOT)

        destination.parent.mkdir(
            parents=True,
            exist_ok=True
        )

        shutil.copy2(file, destination)

    try:
        for file, content in changes:
            file.write_text(
                content,
                encoding="utf-8"
            )

    except Exception:
        # В случае ошибки восстанавливаем
        # все файлы из резервной копии.
        for file, content in changes:
            source = backup / file.relative_to(ROOT)
            shutil.copy2(source, file)

        raise

    print("\nГотово!")
    print("Обновлено страниц:", len(changes))
    print("Резервные копии:", backup)
    print("Проверьте изменения командой git diff.")


if __name__ == "__main__":
    main()
