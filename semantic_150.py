BRIEF_RE = re.compile(
    r'<section\b(?=[^>]*\bid=["\']brief["\'])[^>]*>',
    re.I
)


def update_html(original, path):
    section = create_section(path)

    # Если блок уже создавался,
    # обновляем его вместо добавления второго.
    if START in original or END in original:
        if original.count(START) != 1 or original.count(END) != 1:
            raise ValueError(
                f"Повреждены SEO150-маркеры: {path}"
            )

        pattern = re.compile(
            re.escape(START)
            + r".*?"
            + re.escape(END),
            re.S
        )

        return pattern.sub(
            lambda match: section,
            original,
            count=1
        )

    if 'id="seo-semantic-coverage"' in original:
        raise ValueError(
            f"Блок SEO уже существует без маркеров: {path}"
        )

    matches = list(BRIEF_RE.finditer(original))

    if len(matches) != 1:
        raise ValueError(
            f"Не найден единственный раздел brief: {path}"
        )

    pos = matches[0].start()
    main_start = original.find("<main")
    main_end = original.find("</main>")

    if not (0 <= main_start < pos < main_end):
        raise ValueError(
            f"Раздел brief находится вне main: {path}"
        )

    return (
        original[:pos]
        + "\n" + section + "\n"
        + original[pos:]
    )


