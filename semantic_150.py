def check_sitemap():
    sitemap = ROOT / "sitemap.xml"

    if not sitemap.exists():
        raise FileNotFoundError("Не найден sitemap.xml")

    root = ET.parse(sitemap).getroot()

    urls = set()

    for item in root.findall("./{*}url"):
        loc = item.find("{*}loc")

        if loc is not None and loc.text:
            urls.add(loc.text.strip())

    for path in TERMS:
        expected = "https://saitvdelo.ru" + path

        if expected not in urls:
            raise ValueError(
                f"Страница отсутствует в sitemap: {path}"
            )


def file_for_url(path):
    if path == "/":
        target = ROOT / "index.html"
    else:
        target = ROOT / path.strip("/") / "index.html"

    target = target.resolve()

    if not target.is_relative_to(ROOT.resolve()):
        raise ValueError(
            f"Путь выходит за пределы проекта: {path}"
        )

    if not target.exists():
        raise FileNotFoundError(
            f"Не найден HTML: {target}"
        )

    return target


