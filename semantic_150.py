def create_section(path):
    title, intro, cards, links = content_for_page(path)

    articles = []

    for number, (heading, paragraph) in enumerate(
        cards, start=1
    ):
        articles.append(
            "<article>"
            f"<span>{number:02d}</span>"
            f"<h3>{escape(heading)}</h3>"
            f"<p>{escape(paragraph)}</p>"
            "</article>"
        )

    link_html = []

    for href, label in links:
        link_html.append(
            f'<a href="{escape(href, quote=True)}">'
            f"{escape(label)} <span aria-hidden=\"true\">↗</span>"
            "</a>"
        )

    section = (
        START + "\n"
        '<section id="seo-semantic-coverage" '
        'class="wrap section growth-section" '
        'aria-labelledby="seo-semantic-title">\n'
        '<p class="eyebrow">ПОЛЕЗНО ЗНАТЬ / ВЫБОР САЙТА</p>\n'
        f'<h2 id="seo-semantic-title">{escape(title)}</h2>\n'
        f'<p class="growth-intro">{escape(intro)}</p>\n'
        '<div class="growth-cards">\n'
        + "\n".join(articles)
        + "\n</div>\n"
        '<div class="seo-service-links">\n'
        + "\n".join(link_html)
        + "\n</div>\n"
        "</section>\n"
        + END
    )

    return section


